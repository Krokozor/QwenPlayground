namespace QwenPlayground.Core.Inference;

/// <summary>
/// Детерминированная схема слотов llama.cpp (редакция 2026-09-25, решение владельца):
/// 5 слотов (0-4), сервер запущен с --slots 5.
///
///  · 0 — main (дефолт main-агента, главное окно);
///  · 1-2 — окна: 1 — дефолт не-main сессий главного окна, 2 — ручная разводка
///    контекста нескольких окон (main и не-main — не такая большая разница, оба — окна);
///  · 3 — субагент (spawn_subagent): один на всё приложение, чистится в конце хода;
///  · 4 — пробы (intuition, классификация памяти на собственной модели): собственный
///    слот, потому что проба НЕ меняет кеш чата, но и в чат-слот лезть не может
///    (пере-евалюировала бы его KV).
///
/// Сервисные вызовы (суммаризация/компакция) НЕ имеют своего слота: идут на слоте
/// СУММАРИЗУЕМОЙ сессии — контекст сессии после сжатия меняется в любом случае, а
/// размазывание промптов по отдельному слоту раздувает занятость единого KV-пула и
/// замедляет промпт-обработку всех слотов.
///
/// Почему пиннинг обязателен: при явном id_slot сервер НЕ ходит в RAM prompt cache
/// (b10353: update_cache=false для явного слота) — пиннутый слот живёт в GPU
/// (--no-cache-idle-slots) и защищается только файловым якорем (KvCacheController).
/// ВНИМАНИЕ: невалидный id_slot сервер ТИХО перемапит на слот 0 (проверено живой пробой)
/// — поэтому перед использованием закреплённого слота проверяйте, что он есть (GET /slots).
/// </summary>
public static class SlotAllocation
{
    /// <summary>Main-агент (главное окно, main-сессия): дефолт main-агента.</summary>
    public const int Main = 0;

    /// <summary>Окно 1: не-main сессии главного окна (дефолт не-main).</summary>
    public const int NonMain = 1;

    /// <summary>Окно 2: ручная разводка контекста нескольких окон (вторая сессия/окно).</summary>
    public const int SideWindow = 2;

    /// <summary>Субагент (spawn_subagent): один на всё приложение (синхронная модель).
    /// Слот вычищается в конце хода субагента (KV больше не нужен — отчёт уехал main'у).</summary>
    public const int Subagent = 3;

    /// <summary>Логит-пробы собственной модели (intuition, классификация памяти): собственный
    /// слот, чтобы проба не пере-евалюировала KV чат-слота.</summary>
    public const int Probe = 4;
}
