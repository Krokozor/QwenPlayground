namespace QwenPlayground.Core.Chat;

/// <summary>
/// Группа (полка) инструмента. Core — всегда в системном промпте (базовый набор). Non-core
/// (Browser, CSharp) — активируются по требованию («скилл»): тулзы группы докидываются в промпт
/// только пока полка открыта, чтобы не перегружать внимание и не раздувать KV-кеш.
///
/// Стратегия выключения (минимизация пересчёта KV-кеша):
/// · Активация — немедленная: модель попросила → тулзы группы в промпте со следующего хода
///   (rebuild оправдан — способность явно нужна).
/// · Деактивация — staged: группа помечается в shelves_pending.json, но НЕ снимается сразу.
///   Снятие происходит только когда системный промпт и так меняется (сравнение с кэшем:
///   компакция/смена сессии/изменение слоёв) — деактивация батчится с неизбежным rebuild'ом,
///   а не создаёт собственный.
/// · Пере-активация отменяет pending (группа понадобилась снова → решение на выключение
///   откатывается, rebuild не происходит).
/// · Авто-выключение после компакции: если в оставшемся контексте ни одного ToolCall из
///   инструментов группы — группа снимается (бесплатно: компакция и так пересобирает промпт).
/// </summary>
public enum ToolGroup
{
    /// <summary>Базовый набор: всегда в промпте.</summary>
    Core = 0,

    /// <summary>WebView2-браузер: navigate/click/type/screenshot/extract/JS и т.п.</summary>
    Browser = 1,

    /// <summary>Roslyn: символы, ссылки, callers, диагностика, outline, class map.</summary>
    CSharp = 2
}
