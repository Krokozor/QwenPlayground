using System.IO;

namespace QwenPlayground.App;

/// <summary>
/// «Основной» резидентный агент: постоянная сессия, которая переживает рестарты
/// приложения и в которой живут heartbeat-пробуждения, wake-сигналы и рабочая
/// переписка. Это — долгосрочная память агента.
///
/// Начиная с перехода на слоистую память (2026-08-18) сессия main живёт в отдельной
/// папке sessions/main/: chat.json (история) + layers.json (слои L1/L2/L3) + место
/// под сопутствующие файлы (медиа и т.п.). Идентичность (main-agent.md) и слои
/// инжектятся в системный промпт при сборке, а не пишутся в историю.
/// </summary>
public static class MainAgent
{
    public const string SessionId = "main";
    /// <summary>Имя файла истории main-сессии внутри папки сессии.</summary>
    public const string ChatFileId = "chat";
    public const string IdentityFileName = "main-agent.md";

    /// <summary>
    /// Нейтральная заглушка для свежего клона/форка: файл НЕ персонализирован и не пушится
    /// в git (.gitignore) — каждый владелец описывает свою среду и конвенции сам.
    /// В отличие от trajectory.md (его правит агент), этот файл принадлежит юзеру.
    /// </summary>
    private const string DefaultIdentity = """
        # main-agent — идентичность резидентного агента

        Этот файл — идентичность твоего агента: он инжектится в системный промпт при каждой
        сборке и переживает рестарты и rebuild. Файл принадлежит ТЕБЕ (владельцу клона/форка):
        опиши среду, модели и конвенции, которых агент должен придерживаться.

        ## Среда

        - Workspace: корень проекта (решение в корне, код в `src/`).
        - Инференс: твой LLM-сервер (OpenAI-совместимый API), адрес — в настройках приложения.
        - (Добавь своё: компаньон-модели, дополнительные инструменты, внешние папки.)

        ## Память

        - Долговременная память: `memories/` (один JSON на факт) + `memories/index.md`.
          Решения, починки, важные идентификаторы — сразу в `memory_add`.
        - Слои L1–L3 (`sessions/main/layers.json`) — дистиллят истории main-сессии.
        - Записная книжка проекта — `refactoring.md`: проблемы, changelog, backlog.
        - Траектория — `trajectory.md`: текущая цель и направление (этот файл правит сам агент).

        ## Обязанности на heartbeat

        1. Проверить `refactoring.md`: есть ли незакрытые пункты, которые можно сделать безопасно и локально.
        2. Крупные и рискованные изменения — только по явному запросу.
        3. Если изменил код приложения — завершить ход `rebuild_self`.
        4. Если делать нечего — коротко сообщить статус одной строкой и остановиться.

        ## Правила безопасности

        - Не коммитить без явной просьбы.
        - Не удалять данные пользователя (сессии, логи) без подтверждения.
        - Каталог `run/` не трогать руками — только через rebuild_self.
        - Класс = файл; комментировать несамоочевидное.

        ## Конвенции (допиши свои)

        - (Технические заметки для агента: паттерны проекта, обработка ошибок, инварианты.)
        """;

    /// <summary>
    /// Идентичность из main-agent.md. Свежий клон (файла нет) — создаём нейтральную заглушку
    /// на диске: файл принадлежит юзеру, он (или агент по его просьбе) заполнит её.
    /// </summary>
    public static string LoadIdentity(string workspaceRoot)
    {
        var path = Path.Combine(workspaceRoot, IdentityFileName);
        if (File.Exists(path))
        {
            var text = File.ReadAllText(path).Trim();
            if (text.Length > 0)
            {
                return text;
            }
        }
        try
        {
            File.WriteAllText(path, DefaultIdentity);
        }
        catch
        {
            // Недоступный для записи workspace не должен ронять сборку промпта.
        }
        return DefaultIdentity.Trim();
    }
}
